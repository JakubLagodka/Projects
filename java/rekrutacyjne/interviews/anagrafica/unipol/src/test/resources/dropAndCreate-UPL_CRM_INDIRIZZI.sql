DROP TABLE IF EXISTS UPL_CRM_INDIRIZZI;
CREATE TABLE UPL_CRM_INDIRIZZI
(ID_INDIRIZZO IDENTITY NOT NULL,
	NAZIONE  BIGINT,
    FLAG_PROVENIENZA_BANCA  BIGINT,
    SIGLA_PROVINCIA  BIGINT,
    INDIRIZZO  VARCHAR(100) NOT NULL,
    LOCALITA  VARCHAR(100),
    CRC  VARCHAR(200),
    COMUNE  VARCHAR(50) NOT NULL,
     CAP  VARCHAR(20),
      FLAG_NORMALIZZATO  VARCHAR(1),
      FLAG_NORMALIZZAZIONE_IGNORATA  VARCHAR(1),
       LATITUDINE  VARCHAR(10),
          LONGITUDINE  VARCHAR(10),
           DATA_AGGIORNAMENTO TIMESTAMP,
              UTENTE_AGGIORNAMENTO VARCHAR(20),
     CAP_RESIDENZA_DOMICILIO  VARCHAR(30),
        NUMERO  VARCHAR(16),
        VIA  VARCHAR(64),
        CODICE_BELFIORE  VARCHAR(16),
          CODICE_ISTAT VARCHAR(16),
         CELLA_CENSUARIA  VARCHAR(16),
            PREFISSO_STRADA  VARCHAR(16),
            PROVENIENZA  VARCHAR(50),
            TIPO_INDIRIZZO   BIGINT NOT NULL,
             ID_SOGGETTO   BIGINT NOT NULL,
               FLAG_MEMBRO_FAMIGLIA  VARCHAR(1),
                     FLAG_INDIRIZZO_PRINCIPALE  VARCHAR(1),
                     TIPO_ADDRESS  VARCHAR(1) NOT NULL,
    DATA_INIZIO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    DATA_FINE TIMESTAMP,
    DATA_INSERIMENTO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UTENTE_INSERIMENTO VARCHAR(20) NOT NULL
);
