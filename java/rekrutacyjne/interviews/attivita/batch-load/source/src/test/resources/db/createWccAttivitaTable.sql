DROP TABLE IF EXISTS WCC_ATTIVITA;
CREATE TABLE WCC_ATTIVITA
(
    REQUEST_ID BIGINT NOT NULL AUTO_INCREMENT,
    COD_ISTITUTO INT,
    TIPO_OPERAZIONE CHARACTER,
    FLG_CARICATO INT,
    UPD_TIMESTAMP TIMESTAMP,
    INS_TIMESTAMP TIMESTAMP,
    PROVENIENZA VARCHAR(50),
    ATTIVITA_ID BIGINT,
    SISTEMA_ID VARCHAR(100),
    TIPOATTIVITA_ID BIGINT NOT NULL,
    ATTIVITA_CLIENTE CHAR(1) DEFAULT 'S',
    CREATO_DA_TIPO CHAR(1) NOT NULL,
    CREATO_DA_UTENTE VARCHAR(16) NOT NULL,
    CREATO_DA_NOMINATIVO VARCHAR(100) NOT NULL,
    COMPAGNIA CHAR(1) NOT NULL,
    AGENZIA_MADRE VARCHAR(5) NOT NULL,
    AGENZIA_FIGLIA VARCHAR(5) NOT NULL,
    CFPIVA_CLIENTE VARCHAR(16),
    CONT_ID BIGINT,
    CONTEXT_ID VARCHAR(100),
    REGOLA_ASSEGNAZIONE VARCHAR(3),
    PRIORITA CHAR(1) DEFAULT '2',
    ATTIVITA_ST_TP_CD BIGINT DEFAULT 1,
    AVVIO_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SCADENZA_DT TIMESTAMP,
    COMPLETATA_DT TIMESTAMP,
    FINE_DT TIMESTAMP,
    RIAPERTURA INTEGER DEFAULT 0,
    RIAPERTURA_DT TIMESTAMP,
    ESCALATION CHAR(1) DEFAULT '0',
    ESCALATION_DT TIMESTAMP,
    ASSEGNATORE VARCHAR(16),
    ASSEGNATORE_DESC VARCHAR(100),
    ASSEGNAZIONE CHAR(1),
    ASSEGNATARIO VARCHAR(16),
    ASSEGNATARIO_DESC VARCHAR(100),
    FLAG_ANNOTAZIONE CHAR(1)  DEFAULT 'N',
    ANNOTAZIONE VARCHAR(1050),
    CHIUSA_SCADUTA CHAR(1) DEFAULT 'N',
    LAST_UPDATE_DT TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    DELEGA_CC CHAR(1) DEFAULT 'N',
    DELEGA_CC_ABILITATA CHAR(1) DEFAULT 'N',
    GESTIONE_MC CHAR(1) DEFAULT 'N',
    ID_PROCESSO BIGINT,
    INDICATORE_ICONA INTEGER,
    DELEGA_CC_INIZIALE CHAR(1)
);